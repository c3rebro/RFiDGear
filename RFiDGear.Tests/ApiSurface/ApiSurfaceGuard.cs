#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text;

using Xunit;

namespace RFiDGear.Tests.ApiSurface
{
    /// <summary>
    /// The comparison behind every approved-snapshot test: render an assembly's public surface with
    /// <see cref="ApiSurfaceWriter"/>, compare it with the snapshot checked in next to this file, and fail with a
    /// readable difference. To accept an intended change, run the test once with the environment variable
    /// <c>RFIDGEAR_UPDATE_API_SNAPSHOT=1</c>: it rewrites the snapshot and fails on purpose, so a run with the variable
    /// set can never pass silently. Review the <c>git diff</c> of the snapshot and commit it with the change.
    /// </summary>
    internal static class ApiSurfaceGuard
    {
        private const string UpdateVariable = "RFIDGEAR_UPDATE_API_SNAPSHOT";
        private const string CommentPrefix = "//";

        /// <summary>Compares <paramref name="assembly"/>'s surface with the approved snapshot, or rewrites the snapshot.</summary>
        /// <param name="assembly">The assembly whose public surface is guarded.</param>
        /// <param name="baselineFileName">File name of the snapshot in the <c>ApiSurface</c> folder.</param>
        /// <param name="options">How the writer renders this assembly.</param>
        public static void AssertMatchesSnapshot(Assembly assembly, string baselineFileName, ApiSurfaceOptions? options = null)
        {
            var assemblyName = assembly.GetName().Name;
            var actual = ApiSurfaceWriter.Describe(assembly, options);

            if (Environment.GetEnvironmentVariable(UpdateVariable) == "1")
            {
                var path = SourceBaselinePath(baselineFileName);
                File.WriteAllText(path, Header(assemblyName) + string.Join("\n", actual) + "\n", new UTF8Encoding(false));
                Assert.Fail($"The API snapshot was rewritten at {path}. Review its git diff, commit it with the change, and run the tests again without {UpdateVariable}.");
            }

            var expected = ReadBaseline(baselineFileName);
            if (!expected.SequenceEqual(actual, StringComparer.Ordinal))
            {
                Assert.Fail(DescribeDifference(assemblyName, baselineFileName, expected, actual));
            }
        }

        /// <summary>Reads the approved snapshot from the test output, without its comment lines.</summary>
        /// <param name="baselineFileName">File name of the snapshot in the <c>ApiSurface</c> folder.</param>
        /// <returns>The snapshot lines.</returns>
        public static IReadOnlyList<string> ReadBaseline(string baselineFileName)
        {
            var path = Path.Combine(AppContext.BaseDirectory, "ApiSurface", baselineFileName);
            Assert.True(File.Exists(path), $"The approved snapshot is missing from the test output at {path}.");

            return File.ReadAllLines(path)
                .Where(line => !line.StartsWith(CommentPrefix, StringComparison.Ordinal))
                .ToList();
        }

        private static string Header(string? assemblyName) =>
            $"// Approved public API surface of {assemblyName}. Generated by ApiSurfaceWriter; do not edit by hand.\n" +
            "// To accept an intended change: set RFIDGEAR_UPDATE_API_SNAPSHOT=1, run the ApiSurface tests once,\n" +
            "// review the git diff of this file and commit it together with the change that caused it.\n";

        private static string SourceBaselinePath(string baselineFileName, [CallerFilePath] string thisFile = "") =>
            Path.Combine(Path.GetDirectoryName(thisFile)!, baselineFileName);

        private static string DescribeDifference(
            string? assemblyName,
            string baselineFileName,
            IReadOnlyList<string> expected,
            IReadOnlyList<string> actual)
        {
            static List<string> Missing(IReadOnlyList<string> from, IReadOnlyList<string> other)
            {
                var counts = other.GroupBy(l => l, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);
                var result = new List<string>();
                foreach (var line in from)
                {
                    if (counts.TryGetValue(line, out var left) && left > 0)
                    {
                        counts[line] = left - 1;
                    }
                    else
                    {
                        result.Add(line);
                    }
                }

                return result;
            }

            const int limit = 40;
            var removed = Missing(expected, actual).Where(l => l.Length > 0).ToList();
            var added = Missing(actual, expected).Where(l => l.Length > 0).ToList();
            var text = new StringBuilder();
            text.AppendLine($"The public surface of {assemblyName} no longer matches the approved snapshot.");
            text.AppendLine("Extensions are compiled against this assembly: a removed or changed line breaks extensions that are already built;");
            text.AppendLine("an added line is usually compatible but is still a new commitment.");
            text.AppendLine();
            text.AppendLine($"Only in the approved snapshot ({removed.Count}):");
            foreach (var line in removed.Take(limit))
            {
                text.AppendLine("  - " + line.Trim());
            }

            text.AppendLine($"Only in the current code ({added.Count}):");
            foreach (var line in added.Take(limit))
            {
                text.AppendLine("  + " + line.Trim());
            }

            if (removed.Count == 0 && added.Count == 0)
            {
                text.AppendLine("(only the order or the blank lines differ)");
            }

            text.AppendLine();
            text.AppendLine($"If the change is intended, set {UpdateVariable}=1, run this test once, review the git diff of");
            text.AppendLine($"RFiDGear.Tests/ApiSurface/{baselineFileName}, and commit it with the change and a note on why it is compatible.");
            return text.ToString();
        }
    }
}
